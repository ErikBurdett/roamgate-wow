import fs from 'node:fs/promises';
import path from 'node:path';
export async function bundleUI(source) {
  const names=['Theme','Character','UI','Guide'];
  const parts=await Promise.all(names.map(name=>fs.readFile(path.join(source,`${name}.lua`),'utf8')));
  return '-- Generated by the Roamgate installer. Edit the source modules.\n'+parts.map((text,i)=>`do -- ${names[i]}\n${text}\nend\n`).join('\n');
}
